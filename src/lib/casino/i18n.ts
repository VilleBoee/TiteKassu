export function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  let out = template;
  for (const [key, value] of Object.entries(vars)) out = out.replaceAll(`{${key}}`, String(value));
  return out;
}

export function useI18n() {
  const locale = usePrefs((s) => s.locale);
  const setLocale = usePrefs((s) => s.setLocale);
  const theme = usePrefs((s) => s.theme);
  const toggleTheme = usePrefs((s) => s.toggleTheme);
  const t = useCallback(
    (key: CopyKey, vars?: Record<string, string | number>) => fill(locale === "fi" ? fi[key] : en[key], vars),
    [locale],
  );
  const tx = useCallback((text: string) => localize(locale, text), [locale]);
  const fmt = useCallback((n: number) => formatChips(n, locale), [locale]);
  return { locale, setLocale, theme, toggleTheme, t, tx, fmt };
}
