export function localize(locale: Locale, text: string): string {
  if (locale !== "fi" || !text) return text;
  let out = text;
  for (const [from, to] of phrases) {
    const escaped = from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    out = out.replace(new RegExp(`(?<![\\p{L}])${escaped}(?![\\p{L}])`, "gu"), to);
  }
  return out;
}

